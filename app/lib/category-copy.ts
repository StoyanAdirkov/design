/**
 * Връща описателния текст за категория по нейния handle.
 *
 * Ако няма ръчно написан текст, сглобява кратък абзац от името на
 * категорията и броя продукти. Генеричният вариант нарочно е скромен —
 * няколко изречения, които казват истината, вместо изсипан набор от
 * ключови думи, който търсачките така или иначе разпознават.
 */
export function getCategoryCopy(
  handle: string,
  title: string,
  productCount?: number | null,
  childTitles: string[] = [],
): CategoryCopy | null {
  const hit = COPY[handle];
  if (hit) return hit;

  if (!productCount || productCount < 4) return null;

  const children = childTitles.slice(0, 6).join(', ');
  const paragraphs = [
    `В „${title}“ ще намерите ${new Intl.NumberFormat('bg-BG').format(productCount)} продукта${
      children ? ` — ${children.toLocaleLowerCase('bg-BG')} и още` : ''
    }. Цените са с включено ДДС и важат както онлайн, така и в 26-те ни обекта в страната.`,
    'Ако не откривате нужния артикул или ви трябва количество за цял обект, обадете се на 02 81 80 826 — проверяваме наличността по складове и уточняваме срок.',
  ];
  return {heading: title, paragraphs};
}
